export interface EntityConfig {
  table: string;
  columns: string[];
  toArgs: (rec: any) => any[];
  toRow: (row: any) => any;
}

function nullify(val: any): any {
  return val === undefined ? null : val;
}

function stringifyJson(val: any, fallback: any): string {
  return JSON.stringify(val ?? fallback);
}

function parseJson(text: any, fallback: any): any {
  if (text === null || text === undefined || text === '') return fallback;
  try {
    return JSON.parse(text);
  } catch {
    return fallback;
  }
}

function toBool(val: any): boolean {
  return val === true || val === 1 || val === '1';
}

function progressId(rec: any): string {
  return rec.id ?? `lp_${rec.courseId}_${rec.lessonId}_${rec.traineeId}`;
}

