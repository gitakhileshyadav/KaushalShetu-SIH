import { dbUnavailable, getClient } from '../_lib/db.js';
import { ensureSchema } from '../_lib/schema.js';
import { ENTITIES } from '../_lib/entities.js';
import { json, Req, Res } from '../_lib/reqres.js';

function readBody(req: Req): any {
  if (typeof req.body === 'string') {
    try {
      return JSON.parse(req.body);
    } catch {
      return {};
    }
  }
  return req.body ?? {};
}

function clientIp(req: Req): string {
  const h = req.headers['x-forwarded-for'];
  const raw = Array.isArray(h) ? h[0] : h;
  const first = String(raw ?? '')
    .split(',')[0]
    .trim();
  if (!first || first === 'unknown') return 'unknown';
  const ipv4WithPort = first.match(/^(\d{1,3}(?:\.\d{1,3}){3}):\d+$/);
  if (ipv4WithPort) return ipv4WithPort[1];
  return first;
}

export default async function handler(req: Req, res: Res) {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'POST, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type, Authorization');

  if (req.method === 'OPTIONS') {
    res.status(204).json(null);
    return;
  }
  if (req.method !== 'POST') {
    json(res, 405, { error: 'Method not allowed. Use POST.' });
    return;
  }
  if (dbUnavailable(res)) return;
  const client = getClient()!;
  await ensureSchema();

  const body = readBody(req);
  const token = String(body.token ?? '').trim();
  const traineeId = String(body.traineeId ?? '').trim();
  const method = body.method === 'manual_token' ? 'manual_token' : 'web_qr_scan';
  if (!token || !traineeId) {
    json(res, 400, { success: false, error: 'Both token and traineeId are required.' });
    return;
  }

  try {
    // Step 1: token must match an active qr_tokens row (exact match)
    const tokenRes = await client.execute({
      sql: 'SELECT * FROM qr_tokens WHERE token = ? AND is_active = 1',
      args: [token],
    });
    if (tokenRes.rows.length === 0) {
      json(res, 200, {
        success: false,
        reason: 'invalid',
        message: 'Invalid QR Code token. Please scan an active session QR code generated by your trainer.',
      });
      return;
    }
    const matchedToken = ENTITIES['qr_tokens'].toRow(tokenRes.rows[0]);

    // Step 2: expiry check
    if (new Date(matchedToken.expiresAt) < new Date()) {
      json(res, 200, {
        success: false,
        reason: 'expired',
        message: 'This QR Code token has expired. Ask your trainer to project a refreshed QR code.',
      });
      return;
    }

    // Step 3: associated session must exist
    const sessionRes = await client.execute({
      sql: 'SELECT * FROM sessions WHERE id = ?',
      args: [matchedToken.sessionId],
    });
    if (sessionRes.rows.length === 0) {
      json(res, 200, {
        success: false,
        reason: 'invalid',
        message: 'Associated training session could not be found.',
      });
      return;
    }
    const session = ENTITIES['sessions'].toRow(sessionRes.rows[0]);

    // Step 4: trainee enrollment gate
    const enrollmentRes = await client.execute({
      sql: 'SELECT * FROM enrollments WHERE course_id = ? AND trainee_id = ?',
      args: [session.courseId, traineeId],
    });
    const courseRes = await client.execute({
      sql: 'SELECT * FROM courses WHERE id = ?',
      args: [session.courseId],
    });
    const course = courseRes.rows.length > 0 ? ENTITIES['courses'].toRow(courseRes.rows[0]) : null;

    if (enrollmentRes.rows.length === 0) {
      json(res, 200, {
        success: false,
        reason: 'not_enrolled',
        message: `Attendance rejected: You are not enrolled in "${course?.title || 'this course'}". Request admission first.`,
      });
      return;
    }
    const enrollment = ENTITIES['enrollments'].toRow(enrollmentRes.rows[0]);
    if (enrollment.status === 'pending_approval') {
      json(res, 200, {
        success: false,
        reason: 'pending',
        message: `Attendance rejected: Your enrollment in "${course?.title}" is awaiting trainer approval.`,
      });
      return;
    }
    if (enrollment.status === 'rejected') {
      json(res, 200, {
        success: false,
        reason: 'rejected',
        message: 'Attendance rejected: Your enrollment in this course was rejected.',
      });
      return;
    }

    // Step 5: duplicate prevention
    const countRes = await client.execute({
      sql: 'SELECT COUNT(*) as count FROM attendance_logs WHERE session_id = ? AND trainee_id = ?',
      args: [session.id, traineeId],
    });
    if (Number(countRes.rows[0]?.count ?? 0) > 0) {
      const existingRes = await client.execute({
        sql: 'SELECT scanned_at FROM attendance_logs WHERE session_id = ? AND trainee_id = ? ORDER BY scanned_at DESC LIMIT 1',
        args: [session.id, traineeId],
      });
      const timeStr = new Date(String(existingRes.rows[0]?.scanned_at ?? '')).toLocaleTimeString([], {
        hour: '2-digit',
        minute: '2-digit',
      });
      json(res, 200, {
        success: false,
        reason: 'duplicate',
        message: `Duplicate attendance prevented: You already recorded attendance for this session at ${timeStr}.`,
      });
      return;
    }

    // Step 6: record the verified attendance log
    const traineeRes = await client.execute({
      sql: 'SELECT * FROM users WHERE id = ?',
      args: [traineeId],
    });
    const trainee =
      traineeRes.rows.length > 0 ? ENTITIES['users'].toRow(traineeRes.rows[0]) : null;
    const traineeName = trainee?.fullName || traineeId;

    const newLog = {
      id: `att_log_${Date.now()}`,
      sessionId: session.id,
      courseId: session.courseId,
      traineeId,
      traineeName,
      scannedAt: new Date().toISOString(),
      ipAddress: clientIp(req),
      verified: true,
      method,
    };

    const cfg = ENTITIES['attendance'];
    const columns = cfg.columns.join(', ');
    const placeholders = cfg.columns.map(() => '?').join(', ');
    await client.execute({
      sql: `INSERT INTO ${cfg.table} (${columns}) VALUES (${placeholders})`,
      args: cfg.toArgs(newLog),
    });

    json(res, 200, {
      success: true,
      log: {
        id: newLog.id,
        sessionId: newLog.sessionId,
        courseId: newLog.courseId,
        traineeId: newLog.traineeId,
        traineeName: newLog.traineeName,
        scannedAt: newLog.scannedAt,
        ipAddress: newLog.ipAddress,
        verified: true,
        method: newLog.method,
      },
      session,
      course,
    });
  } catch (err: any) {
    json(res, 500, { success: false, error: String(err?.message ?? err) });
  }
}
